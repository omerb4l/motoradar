// Helper to quickly search across all brands and models simultaneously
export function searchCatalogGlobally(query: string): { brand: MotorcycleBrand; model: MotorcycleModelSpec }[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results: { brand: MotorcycleBrand; model: MotorcycleModelSpec }[] = [];
  for (const brand of MOTORCYCLE_CATALOG) {
    for (const model of brand.models) {
      if (
        brand.brand.toLowerCase().includes(q) ||
        model.name.toLowerCase().includes(q) ||
        `${brand.brand} ${model.name}`.toLowerCase().includes(q)
      ) {
        results.push({ brand, model });
      }
    }
  }
  return results.slice(0, 30);
}
